export function generateStaticParams() {
  return Object.keys(pages).map((page) => ({ page }));
}
export async function generateMetadata({
  params,
}: {
  params: Promise<{ page: string }>;
}) {
  const { page } = await params;
  return { title: pages[page]?.title || "Страница не найдена" };
}
export default async function InfoPage({
  params,
}: {
  params: Promise<{ page: string }>;
}) {
  const { page } = await params;
  const content = pages[page];
  if (!content) notFound();
  const contact = process.env.NEXT_PUBLIC_TELEGRAM_CONTACT;
  const validContact =
    contact && /^https:\/\/t\.me\/[a-zA-Z0-9_]{5,32}$/.test(contact)
      ? contact
      : null;
  return (
    <div className="wrap page-content info-page">
      <div className="page-heading">
        <h1>{content.title}</h1>
        <p>{content.lead}</p>
      </div>
      <div
        className={
          page === "about" ? "info-layout about-layout" : "info-layout"
        }
      >
        {page === "about" && (
          <Photograph
            source="MEDIA-21"
            alt="Свеча в форме объятия, предоставленный референс"
          />
        )}
        <div className="info-sections">
          {content.sections.map((section) => (
            <section key={section.title}>
              <h2>{section.title}</h2>
              <p>{section.text}</p>
            </section>
          ))}
          {page === "contacts" && (
            <div className="contact-actions">
              {validContact ? (
                <a
                  className="button"
                  href={validContact}
                  target="_blank"
                  rel="noopener noreferrer"
                >
                  Написать в Telegram ↗
                </a>
              ) : (
                <p className="notice">
                  Личный Telegram-контакт пока не настроен.
                </p>
              )}
              <a
                className="text-link"
                href="https://t.me/+qQX5YNnktWlkOTIy"
                target="_blank"
                rel="noopener noreferrer"
              >
                Открыть ссылку-приглашение в Telegram ↗
              </a>
            </div>
          )}
          <Link className="text-link" href="/catalog">
            Посмотреть коллекцию ↗
          </Link>
        </div>
      </div>
    </div>
  );
}
